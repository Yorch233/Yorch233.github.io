import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { uiIconCatalog } from '../src/lib/ui-icon-catalog.js';
import { uiIconArtwork } from '../src/lib/ui-icon-artwork.js';
const target = new URL('../public/icons/', import.meta.url);
await mkdir(target, { recursive: true });
const registry = {};
for (const item of uiIconCatalog) {
 const { line, filled } = uiIconArtwork[item.id] || {};
 if (!line || !filled || !filled.includes('data-icon-tone="secondary"')) throw new Error('Missing paired duotone icon: ' + item.id);
 registry[item.id] = { ...item, line, filled };
 for (const [state, body, color] of [['active-filled', filled, item.color], ['inactive', line, '#8591a3']]) {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" style="color:' + color + ';--ui-icon-secondary:' + item.secondary + '">' + body + '</svg>\n';
  await writeFile(new URL(item.id + '-' + state + '.svg', target), svg);
 }
}
// Preserve recognizable brand marks while sharing the site's interaction colors.
const brands = JSON.parse(await readFile(new URL('../node_modules/@iconify-json/simple-icons/icons.json', import.meta.url), 'utf8'));
for (const [id, label] of [['github', 'GitHub'], ['orcid', 'ORCID'], ['huggingface', 'Hugging Face']]) {
 const body = brands.icons[id]?.body;
 if (!body) throw new Error('Missing brand icon: ' + id);
 registry[id] = { id, label, color: '#3189f5', secondary: '#bfdfff', line: body, filled: body };
}
await writeFile(new URL('../src/lib/ui-icons.js', import.meta.url), '// Generated by npm run icons:build. Edit ui-icon-artwork.js and ui-icon-catalog.js.\nexport const uiIcons = ' + JSON.stringify(registry, null, 2) + ';\n');
await writeFile(new URL('manifest.json', target), JSON.stringify(uiIconCatalog.map(item => ({ ...item, variants: Object.fromEntries(['active-filled', 'inactive'].map(state => [state, '/icons/' + item.id + '-' + state + '.svg'])) })), null, 2) + '\n');
// Remove only obsolete exports from this family; keep references and other assets.
for (const name of await readdir(target)) {
 if (uiIconCatalog.some(item => name === item.id + '-active-line.svg')) await unlink(new URL(name, target));
}
console.log('Exported ' + uiIconCatalog.length + ' original icons × 2 states.');
