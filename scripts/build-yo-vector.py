"""Rebuild the faithful pure-SVG Fluffy surface from its approved source.
Run: uv run --with numpy --with scipy --with pillow --with vtracer python scripts/build-yo-vector.py
This is an authoring tool, not part of the production build or browser runtime.
"""
from pathlib import Path
import tempfile
import hashlib
import json
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt, map_coordinates
import vtracer

root = Path(__file__).resolve().parent.parent
source = root / 'public/images/yo/fluffy-body.webp'
image = np.array(Image.open(source).convert('RGBA'))
alpha = image[:, :, 3]
height, width = alpha.shape
# Extend edge colors underneath the silhouette before smoothing; transparent
# black pixels must never contaminate the pale cloud rim.
_, indices = distance_transform_edt(alpha < 240, return_indices=True)
colors = image[:, :, :3][tuple(indices)].astype(float)
with tempfile.TemporaryDirectory(prefix='yo-vector-') as temp:
    matte = Path(temp) / 'alpha.png'
    traced = Path(temp) / 'alpha.svg'
    Image.fromarray(alpha).convert('RGB').save(matte)
    vtracer.convert_image_to_svg_py(str(matte), str(traced), colormode='color',
        hierarchical='stacked', mode='spline', filter_speckle=4, color_precision=6,
        layer_difference=8, corner_threshold=60, length_threshold=3.5, path_precision=2)
    xml = traced.read_text()
    outline = xml[xml.index('>', xml.index('<svg')) + 1:xml.rindex('</svg>')]

def simplify(points, tolerance=.6):
    if len(points) <= 2:
        return points
    a, b = points[0], points[-1]
    errors = [max(abs(p[k] - (a[k] + (b[k]-a[k])*(p[0]-a[0])/(b[0]-a[0]))) for k in range(1,4)) for p in points]
    index = int(np.argmax(errors))
    if errors[index] <= tolerance:
        return [a, b]
    return simplify(points[:index+1])[:-1] + simplify(points[index:])

rows, columns = 32, 48
step = height / rows
paint, bands = [], []
for row in range(rows):
    samples = []
    for column in range(columns + 1):
        point = [[(row+.5)*step], [column*width/columns]]
        rgb = [int(round(float(map_coordinates(colors[:,:,channel], point, order=1, mode='nearest')[0]))) for channel in range(3)]
        samples.append([column/columns, *rgb])
    stops = ''.join(f'<stop offset="{t:.5f}" stop-color="#{r:02x}{g:02x}{b:02x}"/>' for t,r,g,b in simplify(samples))
    paint.append(f'<linearGradient id="YO_REF-row{row}">{stops}</linearGradient>')
    bands.append(f'<rect x="0" y="{row*step:.3f}" width="{width}" height="{step+.02:.3f}" fill="url(#YO_REF-row{row})"/>')
# The blur is a fixed vector paint operation. Animation only transforms the
# complete surface; no filter parameters or path geometry change per frame.
content = f'<defs><filter id="YO_REF-smooth" x="-2%" y="-2%" width="104%" height="104%" color-interpolation-filters="sRGB"><feGaussianBlur stdDeviation="{step*.45:.3f}"/></filter><mask id="YO_REF-alpha" maskUnits="userSpaceOnUse" x="0" y="0" width="{width}" height="{height}">{outline}</mask>'+''.join(paint)+'</defs><g mask="url(#YO_REF-alpha)"><g filter="url(#YO_REF-smooth)" shape-rendering="crispEdges">'+''.join(bands)+'</g></g>'
art = root / 'tmp/yo-vector-v2'
art.mkdir(parents=True, exist_ok=True)
(art/'fluffy-body.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">{content}</svg>\n')
markup = f'<g transform="translate(23.56 47) scale({152.89/width} {126/height})" data-fluffy-surface="true">{content}</g>'
(root/'src/lib/yo-fluffy-svg.js').write_text('// Generated by scripts/build-yo-vector.py. Pure SVG: no raster image data.\nconst artwork = '+json.dumps(markup)+';\nexport function fluffySurface(id) { return artwork.replaceAll("YO_REF", id); }\n')
(art/'source.json').write_text(json.dumps({'source':'public/images/yo/fluffy-body.webp','sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'width':width,'height':height,'gradientBands':rows,'gradientStops':content.count('<stop'),'svgBytes':len(content)},indent=2)+'\n')
print('Pure SVG:', len(content), 'bytes;', content.count('<stop'), 'gradient stops')
